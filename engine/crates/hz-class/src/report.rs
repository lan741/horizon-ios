//! Stub emission: what the Mac/CI transpile tier starts from.
//!
//! For each class we emit a Rust module with one `extern`-free stub per method,
//! carrying the JVM descriptor as a comment and the call targets as `// calls:`
//! lines. This is not a translation — it is the skeleton a human or a coding
//! agent fills in, plus a machine-checkable inventory of everything that has to
//! be accounted for before the class can be dropped from the "unported" list.

use crate::ClassFile;

/// JVM descriptor → rough Rust type, for readability of the stub only.
pub fn rust_type(desc: &str) -> &'static str {
    match desc.chars().next() {
        Some('V') => "()",
        Some('Z') => "bool",
        Some('B') | Some('C') | Some('S') | Some('I') => "i32",
        Some('J') => "i64",
        Some('F') => "f32",
        Some('D') => "f64",
        Some('L') | Some('[') => "Obj",
        _ => "Unknown",
    }
}

/// Split `(ILjava/lang/String;J)V` into `(["i32", "Obj", "i64"], "()")`.
pub fn split_descriptor(desc: &str) -> (Vec<&'static str>, &'static str) {
    let mut args = Vec::new();
    let mut chars = desc.chars().peekable();
    if chars.next() != Some('(') {
        return (args, "Unknown");
    }
    while let Some(c) = chars.next() {
        match c {
            ')' => {
                let rest: String = chars.collect();
                return (args, rust_type(&rest));
            }
            'L' => {
                // skip to ';'
                for n in chars.by_ref() {
                    if n == ';' {
                        break;
                    }
                }
                args.push("Obj");
            }
            '[' => {
                // skip every dimension, then the element type as a whole
                while let Some(n) = chars.peek() {
                    if *n == '[' {
                        chars.next();
                    } else {
                        break;
                    }
                }
                if let Some(el) = chars.next() {
                    if el == 'L' {
                        for n in chars.by_ref() {
                            if n == ';' {
                                break;
                            }
                        }
                    }
                }
                args.push("Obj");
            }
            other => args.push(rust_type(&other.to_string())),
        }
    }
    (args, "Unknown")
}

pub fn emit_module(cf: &ClassFile) -> String {
    let mut s = String::new();
    s.push_str(&format!(
        "//! Stub for `{}` (class file v{}.{}, super `{}`).\n\
         //! Generated by `hz stubs`; bodies are intentionally unimplemented.\n\
         //!\n\
         //! Porting checklist for this class:\n\
         //! 1. give every method below a body that matches its descriptor,\n\
         //! 2. replace `Obj` with a concrete handle type,\n\
         //! 3. add it to the pack's `mixin` table if the engine has a hook site,\n\
         //! 4. delete it from the `unported` list in the build manifest.\n\n",
        cf.dotted(),
        cf.major,
        cf.minor,
        if cf.super_name.is_empty() {
            "none"
        } else {
            cf.super_name.as_str()
        }
    ));
    if !cf.interfaces.is_empty() {
        s.push_str(&format!("// interfaces: {}\n\n", cf.interfaces.join(", ")));
    }

    for m in &cf.methods {
        if m.name.starts_with('<') {
            continue; // <init>/<clinit>
        }
        let (args, ret) = split_descriptor(&m.descriptor);
        let params: Vec<String> = args
            .iter()
            .enumerate()
            .map(|(i, t)| format!("a{}: {}", i, t))
            .collect();
        s.push_str(&format!(
            "/// `{}` — {} bytes of bytecode, max_stack {}, max_locals {}\n",
            m.descriptor, m.code_len, m.max_stack, m.max_locals
        ));
        if !m.calls.is_empty() {
            let list: Vec<String> = m
                .calls
                .iter()
                .take(16)
                .map(|(o, n)| format!("{}.{}", o, n))
                .collect();
            s.push_str(&format!("/// calls: {}\n", list.join(", ")));
        }
        let attrs = if m.is_static() {
            "pub fn"
        } else {
            "pub fn /* &self */"
        };
        s.push_str(&format!(
            "{} {}({}) -> {} {{\n    todo!(\"port {}.{}\")\n}}\n\n",
            attrs,
            m.name,
            params.join(", "),
            ret,
            cf.name,
            m.name
        ));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sample::tiny_class;

    #[test]
    fn descriptor_splitting() {
        let (args, ret) = split_descriptor("(ILjava/lang/String;J)V");
        assert_eq!(args, vec!["i32", "Obj", "i64"]);
        assert_eq!(ret, "()");
        let (args, ret) = split_descriptor("([B)Z");
        assert_eq!(args, vec!["Obj"]);
        assert_eq!(ret, "bool");
    }

    #[test]
    fn emits_a_todo_per_method() {
        let bytes = tiny_class("example/Subject", "java/lang/System", "gc");
        let cf = crate::parse(&bytes).unwrap();
        let src = emit_module(&cf);
        assert!(src.contains("pub fn run() -> ()"));
        assert!(src.contains("todo!(\"port example/Subject.run\")"));
        assert!(src.contains("calls: java/lang/System.gc"));
        assert!(src.contains("class file v65.0"));
    }
}
